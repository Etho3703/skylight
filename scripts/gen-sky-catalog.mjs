// Regenerate shared/src/skyCatalog.ts (naked-eye stars + the 88 IAU
// constellation figures) from the d3-celestial data files.
//   node scripts/gen-sky-catalog.mjs <dir with stars.6.json, constellations.json, constellations.lines.json>
// Source: https://github.com/ofrohn/d3-celestial/tree/master/data (BSD-3-Clause,
// (c) 2015 Olaf Frohn). d3-celestial stores RA as -180..180 degrees; we store 0..360.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/gen-sky-catalog.mjs <data dir>");
  process.exit(1);
}
const read = (f) => JSON.parse(readFileSync(join(src, f), "utf8"));
const ra = (x) => Math.round((((x % 360) + 360) % 360) * 100) / 100;
const dec = (x) => Math.round(x * 100) / 100;

// Stars, brightest first so a magnitude cut can stop early.
const stars = read("stars.6.json")
  .features.map((f) => [ra(f.geometry.coordinates[0]), dec(f.geometry.coordinates[1]), f.properties.mag])
  .filter((s) => Number.isFinite(s[2]) && s[2] <= 6)
  .sort((a, b) => a[2] - b[2]);

// Serpens comes as two features with the same id (Caput, then Cauda) in both
// files, so pair each line feature with the next unused name feature.
const names = new Map();
for (const f of read("constellations.json").features) {
  if (!names.has(f.id)) names.set(f.id, []);
  names.get(f.id).push(f);
}
const seen = new Map();
const figures = read("constellations.lines.json").features.map((f) => {
  const n = seen.get(f.id) ?? 0;
  seen.set(f.id, n + 1);
  const meta = names.get(f.id)?.[n];
  return {
    id: n ? `${f.id}${n + 1}` : f.id,
    name: meta?.properties.name ?? f.id,
    rank: Number(meta?.properties.rank ?? 3),
    label: meta ? [ra(meta.geometry.coordinates[0]), dec(meta.geometry.coordinates[1])] : null,
    lines: f.geometry.coordinates.map((line) => line.flatMap(([r, d]) => [ra(r), dec(d)])),
  };
});

const out = `// GENERATED by scripts/gen-sky-catalog.mjs - do not edit by hand.
// Star positions + IAU constellation figures from d3-celestial
// (https://github.com/ofrohn/d3-celestial, BSD-3-Clause, (c) 2015 Olaf Frohn).
// J2000 RA/Dec in degrees (RA 0..360).

/** Flat [ra, dec, mag, ra, dec, mag, ...], brightest first, mag <= 6. */
export const STARFIELD: readonly number[] = ${JSON.stringify(stars.flat())};

export interface ConstellationFigure {
  /** IAU abbreviation, e.g. "Ori". */
  id: string;
  name: string;
  /** 1 = most prominent, 3 = faint. */
  rank: number;
  /** Where to put the name, [ra, dec]. */
  label: [number, number] | null;
  /** Polylines, each flat [ra, dec, ra, dec, ...]. */
  lines: number[][];
}

export const CONSTELLATION_FIGURES: readonly ConstellationFigure[] = ${JSON.stringify(figures)};
`;
const here = dirname(fileURLToPath(import.meta.url));
const dest = resolve(here, "../shared/src/skyCatalog.ts");
writeFileSync(dest, out);
console.log(`wrote ${dest}: ${stars.length} stars, ${figures.length} constellations`);
